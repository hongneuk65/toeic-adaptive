require('reflect-metadata');
require('../dist/config/environment');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { resolve } = require('node:path');
const { execFileSync } = require('node:child_process');
const { PrismaClient } = require('@prisma/client');
const { FlashcardService } = require('../dist/flashcard/flashcard.service');
const schema = `recall_test_${randomUUID().replaceAll('-', '')}`;
const admin = new PrismaClient();
let db;
(async () => {
  const url = new URL(process.env.DATABASE_URL);
  assert.ok(['localhost', '127.0.0.1'].includes(url.hostname));
  url.searchParams.set('schema', schema);
  execFileSync(process.execPath, [resolve(__dirname, '../node_modules/prisma/build/index.js'), 'db', 'push', '--skip-generate'], { cwd: resolve(__dirname, '..'), env: { ...process.env, DATABASE_URL: url.toString() }, stdio: 'pipe', timeout: 60000 });
  db = new PrismaClient({ datasources: { db: { url: url.toString() } } });
  const user = await db.user.create({ data: { email: 'recall@example.invalid', passwordHash: 'fixture' } });
  const other = await db.user.create({ data: { email: 'other@example.invalid', passwordHash: 'fixture' } });
  const folder = await db.flashcardFolder.create({ data: { userId: user.id, name: 'Recall', private: true } });
  const card = await db.flashcard.create({ data: { folderId: folder.id, word: 'Purchase order', meaning: 'đơn đặt hàng' } });
  const service = new FlashcardService(db);
  const attempt = { attemptId: randomUUID(), recallMode: 'typed', response: '  PURCHASE   ORDER ', elapsedMs: 5000 };
  const [first, retry] = await Promise.all([service.review(user.id, card.id, false, attempt), service.review(user.id, card.id, false, attempt)]);
  assert.equal(first.known, true, 'Server grades typed response, ignoring advisory known');
  assert.equal(new Date(first.dueAt).toISOString(), new Date(retry.dueAt).toISOString());
  assert.equal(await db.flashcardRecallEvent.count(), 1);
  assert.equal(first.schedulingSource, 'hlr-prior-experimental');
  await assert.rejects(service.review(user.id, card.id, true, { ...attempt, response: 'wrong' }), /khác/);
  await assert.rejects(service.review(other.id, card.id, false, { ...attempt, attemptId: randomUUID() }));
  await db.flashcardReview.update({ where: { id: first.id }, data: { lastPracticedAt: new Date(Date.now() - 86400000) } });
  const wrong = await service.review(user.id, card.id, true, { ...attempt, attemptId: randomUUID(), response: 'invoice' });
  assert.equal(wrong.known, false);
  assert.equal(wrong.recallWins, 1);
  assert.equal(wrong.recallLosses, 1);
  const event = await db.flashcardRecallEvent.findFirst({ where: { correct: false } });
  assert.ok(event.lagDays >= 1 && event.predictedRecall > 0 && event.predictedRecall < 1);
  assert.ok(Math.abs(new Date(wrong.dueAt).getTime() - Date.now() - 600000) < 5000);
  const self = await service.review(user.id, card.id, true, { attemptId: randomUUID(), recallMode: 'self_report' });
  assert.equal(self.schedulingSource, 'fixed-interval');
  assert.equal(self.recallWins, 1, 'Self-report is excluded from objective recall counts');
  await db.flashcard.update({ where: { id: card.id }, data: { word: 'Invoice' } });
  const edited = await service.review(user.id, card.id, false, { ...attempt, attemptId: randomUUID(), response: 'invoice' });
  assert.equal(edited.recallWins, 1, 'Edited content resets old content evidence');
  assert.equal(edited.recallLosses, 0);
  await assert.rejects(service.review(user.id, card.id, false, { recallMode: 'typed', response: '' }));
  console.log('PASS: server grading, concurrent retry, immutable attempt, access control, delayed evidence, failure scheduling, self-report separation, content reset');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => {
  if (db) await db.$disconnect();
  assert.match(schema, /^recall_test_[a-f0-9]{32}$/);
  await admin.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
  await admin.$disconnect();
});
