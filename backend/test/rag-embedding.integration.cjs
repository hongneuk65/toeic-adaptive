// Isolated PostgreSQL persistence test; no provider calls or application data changes.
require('../dist/config/environment');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { resolve } = require('node:path');
const { PrismaClient } = require('@prisma/client');
const { KnowledgeEmbeddingService } = require('../dist/rag/knowledge-embedding.service');
const { TutorKnowledgeService, knowledgeHash } = require('../dist/rag/tutor-knowledge.service');
const schema = `rag_test_${randomUUID().replaceAll('-', '')}`;
const admin = new PrismaClient();
let db, created = false;
(async () => {
  const url = new URL(process.env.DATABASE_URL);
  assert.ok(['localhost', '127.0.0.1'].includes(url.hostname), 'Use a local test database');
  await admin.$executeRawUnsafe(`CREATE SCHEMA "${schema}"`); created = true;
  url.searchParams.set('schema', schema);
  execFileSync(process.execPath, [resolve(__dirname, '../node_modules/prisma/build/index.js'), 'migrate', 'deploy'], { cwd: resolve(__dirname, '..'), env: { ...process.env, DATABASE_URL: url.toString() }, stdio: 'pipe', timeout: 60000 });
  db = new PrismaClient({ datasources: { db: { url: url.toString() } } });
  const data = { title: 'Although', content: 'Although introduces a clause.', part: 5, skillCode: null, category: 'Grammar', keywords: ['although'], lessonId: null, sourceUri: 'https://example.org/contrast', sourceVersion: 'v1' };
  const source = await db.knowledgeChunk.create({ data: { ...data, reviewStatus: 'APPROVED', reviewedAt: new Date(), reviewedBy: 'integration-fixture', approvedContentHash: knowledgeHash(data) } });
  const embeddings = new KnowledgeEmbeddingService(db);
  Object.defineProperty(embeddings, 'enabled', { value: true });
  embeddings.embed = async () => [1, ...Array(767).fill(0)];
  const tutor = new TutorKnowledgeService(db, embeddings);
  await embeddings.index(source);
  await embeddings.index(source);
  assert.equal(await db.knowledgeEmbedding.count(), 1, 'reindex replaces atomically');
  assert.equal((await tutor.retrieve('hai ý trái ngược', [], 5))[0].id, `K${source.id}@v1`);
  await db.knowledgeChunk.update({ where: { id: source.id }, data: { reviewStatus: 'REVOKED' } });
  assert.deepEqual(await tutor.retrieve('although', [], 5), []);
  await db.knowledgeChunk.update({ where: { id: source.id }, data: { reviewStatus: 'APPROVED', content: 'Changed after review.' } });
  assert.deepEqual(await tutor.retrieve('although', [], 5), [], 'edited source fails hash verification');
  const revised = { ...data, content: 'Changed after review.', sourceVersion: 'v2' };
  const current = await db.knowledgeChunk.update({ where: { id: source.id }, data: { ...revised, approvedContentHash: knowledgeHash(revised) } });
  assert.deepEqual(await tutor.retrieve('hai ý trái ngược', [], 5), [], 'old vectors ignored after new approval');
  await embeddings.index(current);
  assert.equal((await tutor.retrieve('hai ý trái ngược', [], 5))[0].version, 'v2');
  const oldIndex = await db.knowledgeEmbedding.findMany();
  embeddings.embed = async () => { throw new Error('provider unavailable'); };
  await assert.rejects(embeddings.index(current));
  assert.deepEqual(await db.knowledgeEmbedding.findMany(), oldIndex, 'failed index preserves usable prior index');
  await db.knowledgeChunk.delete({ where: { id: source.id } });
  assert.equal(await db.knowledgeEmbedding.count(), 0, 'source deletion cascades');
  console.log('PASS: migration, vector persistence, atomic/idempotent reindex, semantic retrieval, revocation/edit/hash invalidation, provider failure, cascade');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (db) await db.$disconnect();
  if (created) await admin.$executeRawUnsafe(`DROP SCHEMA "${schema}" CASCADE`);
  await admin.$disconnect();
});
